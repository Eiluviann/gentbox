"""Build design/project/sf-symbols.js from SF Pro and the SF Symbols name map.

Usage: python3 -I design/tools/build-symbols.py <map.tsv> <icons.json> <out.js>
map.tsv comes from match.swift (name, PUA codepoint); icons.json from extract.py.
Glyphs are normalised to a 100-unit square frame; a dotted symbol name becomes
an underscore key (bell.badge -> bell_badge) so templates can use {{ic.bell_badge}}.
"""
import json, re, sys
from pathlib import Path

ZED_ICONS = Path.home() / 'Library/Application Support/Zed/external_agents/registry/icons'

def split_badge(path):
	subpaths = re.findall(r'M[^M]*', path)
	def min_x(sub):
		return min(float(v) for v in re.findall(r'-?\d+\.?\d*', sub)[0::2])
	dot = max(subpaths, key=min_x)
	return ''.join(s for s in subpaths if s is not dot), dot

def brand(file_name):
	svg = (ZED_ICONS / file_name).read_text()
	return {
		'vb': re.search(r'viewBox="([^"]+)"', svg).group(1),
		'd': re.search(r' d="([^"]+)"', svg).group(1).replace('\n', ' '),
	}

icons = json.loads(Path(sys.argv[2]).read_text())
symbols = {name.replace('.', '_'): d for name, d in icons.items()}
for name in ('bell.badge', 'bell.badge.fill'):
	body, dot = split_badge(icons[name])
	key = name.replace('.', '_')
	symbols[key + '_body'], symbols[key + '_dot'] = body, dot
# The Gentbox mark: a custom symbol built from bubble.left with a terminal prompt drawn as strokes
symbols['agent_bubble'] = icons['bubble.left']
symbols['agent_prompt'] = 'M28 24L42 37.5L28 51M50 51L68 51'
symbols['agent_dot'] = 'M84 2A14 14 0 1 1 84 30A14 14 0 1 1 84 2Z'
symbols['agent_slash'] = 'M10 6L90 94'
marks = {'claude': brand('claude-acp.svg'), 'codex': brand('codex-acp.svg')}
Path(sys.argv[3]).write_text(
	'// SF Symbols outlines from SF Pro (regular, opsz 17) in a 100-unit frame, for mockups only.\n'
	'// Generated by design/tools/build-symbols.py; do not edit by hand.\n'
	f'window.SF_SYMBOLS = {json.dumps(symbols, separators=(",", ":"))};\n'
	f'window.BRAND_MARKS = {json.dumps(marks, separators=(",", ":"))};\n'
)
print(len(symbols), 'symbols')
