"""Write the dark twin of every v1 board and lay the canvas out left to right.

Usage: python3 -I design/tools/make-dark.py
Each <board>-dark.dc.html is its light board with data-theme="dark" on the root, so
edit the light board and rerun; links between boards stay in the same appearance.
project/canvas.json gets one group per surface: light boards in a row, their dark
twins in the row below, groups side by side, then the light-only mobile group.
"""
import json, re
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent / 'project'
GENERATED = '<!-- Generated by design/tools/make-dark.py from {light}; edit that board and rerun -->\n'
COLUMN_GAP, ROW_GAP, GROUP_GAP, TITLE_OFFSET = 80, 200, 320, 300

# Groups left to right: (note id, title, boards with a dark twin, boards without one)
GROUPS = [
	('group-foundations', 'Foundations and menu bar', ['mac-menubar-icons.dc.html'], ['Main.dc.html']),
	('group-popover', 'Popover', [
		'mac-popover.dc.html', 'mac-popover-accordion.dc.html', 'mac-popover-undo.dc.html',
		'mac-popover-steps.dc.html', 'mac-popover-item-menu.dc.html', 'mac-popover-dismiss.dc.html',
		'mac-popover-empty.dc.html',
	], []),
	('group-popups', 'Popups', [
		'mac-blocking-popup.dc.html', 'mac-blocking-stacked.dc.html', 'mac-blocking-reply.dc.html',
		'mac-blocking-no-waiter.dc.html', 'mac-popup-deferrable.dc.html', 'mac-popup-rescinded.dc.html',
	], []),
	('group-notifications', 'Toast, notifications and silent rows', [
		'mac-completion-toast.dc.html', 'mac-native-banner.dc.html', 'mac-native-banner-expanded.dc.html',
		'mac-generic-row.dc.html',
	], []),
	('group-window', 'Main window', [
		'mac-topic.dc.html', 'mac-thread.dc.html', 'mac-conversation.dc.html', 'mac-outcomes.dc.html',
	], []),
	('group-settings', 'Settings, inside the main window', [
		'settings-notifications.dc.html', 'settings-quiet-focus.dc.html', 'settings-sources.dc.html',
		'settings-rules.dc.html', 'settings-rules-error.dc.html', 'settings-phone.dc.html',
	], []),
]
MOBILE_NOTE = 'group-phone'
TITLES = {
	'mac-popover.dc.html': 'Popover · accordion, next up open',
	'mac-popover-accordion.dc.html': 'Popover · accordion, another item opened',
	'mac-popover-dismiss.dc.html': 'Popover · Close leads to the open items; dismiss several',
	'mac-popover-item-menu.dc.html': 'Popover · item menu, mute, close and dismiss',
}


def main():
	canvas_path = PROJECT / 'canvas.json'
	canvas = json.loads(canvas_path.read_text())
	twins = [name for _, _, dark, _ in GROUPS for name in dark]
	for name in twins:
		write_dark_twin(name, twins)
	canvas['boards'] = lay_out(canvas, twins)
	canvas['order'] = list(canvas['boards'])
	canvas_path.write_text(json.dumps(canvas, indent='\t', ensure_ascii=False) + '\n')
	print('dark twins:', len(twins), 'boards:', len(canvas['boards']))


def write_dark_twin(name, twins):
	html = (PROJECT / name).read_text()
	html, pinned = re.subn(r'data-theme="light"', 'data-theme="dark"', html, count=1)
	if not pinned:
		raise SystemExit(f'{name}: no data-theme="light" on its root')
	html = re.sub(r'<title>(.*?)</title>', r'<title>\1, dark</title>', html, count=1)
	for target in twins:
		html = html.replace(f'href="{target}"', f'href="{dark_name(target)}"')
	html = html.replace('<!doctype html>\n', '<!doctype html>\n' + GENERATED.format(light=name), 1)
	(PROJECT / dark_name(name)).write_text(html)


def lay_out(canvas, twins):
	old = canvas['boards']
	boards, notes, x = {}, canvas.setdefault('notes', {}), 0
	for note_id, title, dark, light_only in GROUPS:
		row = light_only + dark
		row_height = max(old_or_new(old, name)['h'] for name in row)
		left = x
		for name in row:
			frame = dict(old_or_new(old, name), x=x, y=0)
			frame['title'] = TITLES.get(name, frame.get('title', name))
			boards[name] = frame
			if name in dark:
				boards[dark_name(name)] = dict(frame, y=row_height + ROW_GAP, title=frame['title'] + ' · dark')
			x += frame['w'] + COLUMN_GAP
		notes[note_id] = {'x': left, 'y': -TITLE_OFFSET, 'text': title, 'kind': 'title1', 'maxW': x - COLUMN_GAP - left}
		x += GROUP_GAP - COLUMN_GAP
	mobile = [name for name in old if name not in boards and not name.endswith('-dark.dc.html')]
	shift = x - min(old[name]['x'] for name in mobile)
	for name in mobile:
		boards[name] = dict(old[name], x=old[name]['x'] + shift)
	right = max(f['x'] + f['w'] for f in boards.values())
	notes[MOBILE_NOTE] = dict(notes[MOBILE_NOTE], x=x, maxW=right - x)
	notes['mobile-dark-later'] = {
		'x': x, 'y': -170, 'w': 520, 'size': 'm', 'fill': 'gray',
		'text': 'These stay light for now: dark mode for the iPhone and Watch comes with the mobile release',
	}
	for stale in ('group-mac',):
		notes.pop(stale, None)
	return boards


def old_or_new(old, name):
	"""The board's frame, sized from its $preview so a resized board keeps its frame in step."""
	frame = dict(old.get(name, {}))
	preview = re.search(r'"\$preview":\{"width":(\d+),"height":(\d+)\}', (PROJECT / name).read_text())
	if preview:
		frame.update(w=int(preview.group(1)), h=int(preview.group(2)))
	return frame


def dark_name(name):
	return name.replace('.dc.html', '-dark.dc.html')


main()
